"""
SQL Validator & Guardrail Module (Hardened & AST-Backed)
Ensures queries generated by the LLM are strictly safe, read-only (SELECT) statements.
Prevents SQL injection, destructive statements (DROP, DELETE, UPDATE, ALTER, etc.),
command-level exploits (PRAGMA, ATTACH, load_extension), and memory exhaustion via auto-LIMIT.
"""

from typing import Tuple
import re
import sqlglot
from sqlglot import exp

# Destructive AST node types that must NEVER exist anywhere in the syntax tree
DESTRUCTIVE_EXPRESSIONS = (
    exp.Insert,
    exp.Update,
    exp.Delete,
    exp.Drop,
    exp.Create,
    exp.Alter,
    exp.Command,
    exp.Pragma,
)

# Block hazardous functions that can execute external code or load C extensions
DANGEROUS_FUNCTIONS = {
    "load_extension",
    "pg_read_file",
    "pg_write_file",
    "sys_eval",
    "xp_cmdshell"
}

# Block destructive top-level statement keywords
TOP_LEVEL_DML_DDL = {
    "DROP", "DELETE", "UPDATE", "INSERT", "ALTER", "TRUNCATE",
    "GRANT", "REVOKE", "CREATE", "EXEC", "EXECUTE", "ATTACH", "DETACH", "PRAGMA"
}

def clean_sql_input(sql_query: str) -> str:
    """Removes markdown code fences, trailing semicolons, and surrounding whitespace."""
    clean = sql_query.strip()
    if clean.startswith("```"):
        lines = clean.splitlines()
        if lines and lines[0].startswith("```"):
            lines = lines[1:]
        if lines and lines[-1].startswith("```"):
            lines = lines[:-1]
        clean = "\n".join(lines).strip()
    return clean.rstrip(";").strip()

def validate_sql_query(sql_query: str, max_limit: int = 100, dialect: str = "sqlite") -> Tuple[bool, str]:
    """
    Validates a SQL query for safety using Abstract Syntax Tree (AST) analysis.
    
    Guarantees:
    1. Single-statement execution only.
    2. Strict Read-Only semantics (SELECT / WITH CTE only).
    3. No destructive AST nodes (DROP, DELETE, UPDATE, ALTER, etc.).
    4. Legitimate SQL string functions (e.g. REPLACE) and string literals are allowed.
    5. Automatic DoS protection: Enforces a maximum LIMIT (default 100).
    6. Dialect-aware parsing and formatting (SQLite, MySQL).
    
    Returns:
        (True, safe_sql_query_with_limit) if safe.
        (False, error_reason) if unsafe.
    """
    if not sql_query or not sql_query.strip():
        return False, "Empty SQL query."

    clean_query = clean_sql_input(sql_query)
    upper_query = clean_query.upper()

    # 1. Fast-path check: Must start with SELECT or WITH
    if not (upper_query.startswith("SELECT") or upper_query.startswith("WITH")):
        # Check if first word is a known DML/DDL keyword for a user-friendly error
        first_token = upper_query.split()[0] if upper_query.split() else ""
        if first_token in TOP_LEVEL_DML_DDL:
            return False, f"Prohibited operation '{first_token}'. Only read-only SELECT operations are permitted."
        return False, "Query must strictly start with 'SELECT' or 'WITH'. Only read-only operations are permitted."

    # 2. Prevent Multiple SQL statements (Semicolon injection)
    # Split by semicolon outside quotes
    parts = [p.strip() for p in clean_query.split(";") if p.strip()]
    if len(parts) > 1:
        return False, "Multiple SQL statements in a single execution are prohibited for security."

    # 3. Deep AST Validation using sqlglot
    glot_dialect = "mysql" if "mysql" in (dialect or "").lower() else "sqlite"
    try:
        parsed_expressions = sqlglot.parse(clean_query, read=glot_dialect)
        if not parsed_expressions:
            return False, "Failed to parse query syntax into a valid SQL tree."
        
        if len(parsed_expressions) > 1:
            return False, "Multiple SQL statements detected via AST analysis."

        root = parsed_expressions[0]

        # Ensure the root statement is SELECT or UNION
        if not isinstance(root, (exp.Select, exp.Union)):
            return False, f"Query parsed as non-SELECT operation ({type(root).__name__}). Rejected."

        # Scan for any nested destructive expressions (subqueries or CTE injection)
        for dangerous_type in DESTRUCTIVE_EXPRESSIONS:
            if root.find(dangerous_type):
                return False, f"Forbidden destructive AST expression detected: {dangerous_type.__name__}"

        # Check for dangerous function calls (load_extension, etc.)
        for func in root.find_all(exp.Func):
            func_name = (func.name or "").lower()
            if func_name in DANGEROUS_FUNCTIONS:
                return False, f"Hazardous database function '{func_name}' is blocked."

        # 4. DoS Protection: Auto-enforce LIMIT clause
        # If no LIMIT is set, inject LIMIT 100 to prevent OOM/runaway queries
        if isinstance(root, (exp.Select, exp.Union)):
            current_limit = root.args.get("limit")
            if not current_limit:
                root = root.limit(max_limit)
            else:
                # If a limit is already set, ensure it doesn't exceed 1000
                try:
                    limit_val = int(current_limit.expression.this)
                    if limit_val > 1000:
                        root = root.limit(1000)
                except Exception:
                    pass

        # Return standardized, safe SQL in the target dialect
        safe_sql = root.sql(dialect=glot_dialect)
        return True, safe_sql

    except sqlglot.errors.ParseError as pe:
        return False, f"SQL syntax parsing error: {str(pe)}"
    except Exception as e:
        return False, f"Security AST validation error: {str(e)}"

if __name__ == "__main__":
    test_queries = [
        ("SELECT * FROM students WHERE roll_no = 5;", True, "Standard SELECT with auto-limit"),
        ("DROP TABLE students;", False, "Top level DROP statement"),
        ("SELECT * FROM students; DELETE FROM marks;", False, "Multi-statement injection"),
        ("UPDATE students SET name = 'Hacker';", False, "UPDATE statement"),
        ("WITH TopStudents AS (SELECT * FROM students) SELECT * FROM TopStudents;", True, "CTE WITH expression"),
        ("SELECT REPLACE(name, 'Dr.', '') FROM students;", True, "Legitimate string function REPLACE"),
        ("SELECT * FROM audit_log WHERE action = 'UPDATE';", True, "Legitimate string literal containing UPDATE"),
        ("SELECT load_extension('malicious.so');", False, "Dangerous load_extension function")
    ]
    
    print("=== RUNNING HARDENED SQL VALIDATOR TESTS ===")
    all_passed = True
    for query, expected_safe, description in test_queries:
        is_safe, result = validate_sql_query(query)
        passed = (is_safe == expected_safe)
        if not passed:
            all_passed = False
        status = "[PASS]" if passed else "[FAIL]"
        print(f"{status} [{description}] -> Safe: {is_safe} | Output: {result[:50]}...")
    
    print(f"\nFinal Test Status: {'ALL PASSED' if all_passed else 'SOME FAILED'}")
